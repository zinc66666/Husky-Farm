// Словари для генерации ников соседей.

export const ADJ = [
  'Тёмный', 'Быстрый', 'Тихий', 'Ночной', 'Ледяной', 'Дикий', 'Хитрый', 'Злой',
  'Добрый', 'Смелый', 'Сонный', 'Красный', 'Синий', 'Зелёный', 'Пиксельный',
  'Кибер', 'Нео', 'Мега', 'Ультра', 'Тихо', 'Северный', 'Южный', 'Старый',
];

export const NOUN = [
  'Лис', 'Волк', 'Кот', 'Ёж', 'Барс', 'Сокол', 'Ворон', 'Мамонт', 'Хаски',
  'Бобр', 'Тигр', 'Крот', 'Дракон', 'Робот', 'Ниндзя', 'Самурай', 'Пилот',
  'Гоблин', 'Титан', 'Призрак', 'Странник', 'Механик',
];

export function makeName(rnd) {
  const adj = rnd.pick(ADJ);
  const noun = rnd.pick(NOUN);
  const num = rnd.chance(0.55) ? String(rnd.int(1, 99)) : '';
  return `${adj}${noun}${num}`;
}
